def _basic_clean(name: str) -> str:
    s = re.sub(r"\s+", " ", str(name)).strip()
    s = re.sub(r"^(서강대학교|서강대|서강)\s+", "", s)
    s = re.sub(r"\s*[\(（][^)）]*[\)）]\s*$", "", s)  # 말미 괄호 주석
    return s.replace("∙", "·").strip()


def _strip_suffix(s: str) -> str:
    # "법학전문대학원 행정팀" → "법학전문대학원" (앞에 상위 조직명이 남는 경우만)
    for suf in _SUFFIXES:
        for sep in (" ", ""):
            if s.endswith(sep + suf) and len(s) > len(sep + suf):
                head = s[: len(s) - len(sep + suf)].strip(" /·,")
                if len(head) >= 2:
                    return head
    return s


def rule_normalize(name):
    """규칙 기반 정규화 (Gemini 매핑이 없을 때의 폴백)."""
    if name is None or not isinstance(name, str) or not name.strip():
        return None
    s = _basic_clean(name)
    s = ALIAS.get(s, s)
    s = _strip_suffix(s)
    return ALIAS.get(s, s)


@lru_cache(maxsize=1)
def load_org_map() -> dict:
    """Gemini 조직명 매핑 (raw 표기 → 조직도 단위명 | None). 파일이 없으면 빈 dict."""
    if ORG_MAP_PATH.exists():
        return json.loads(ORG_MAP_PATH.read_text(encoding="utf-8"))
    return {}


def resolve_org(name):
    """원본 organization 표기 → 대표 조직명.

    Gemini 매핑에 조직도 단위가 있으면 그 단위명(조직도 공식 표기)을,
    아니면 규칙 기반 정규화 결과를 쓴다.
    """
    if name is None or not isinstance(name, str) or not name.strip():
        return None
    unit = load_org_map().get(name.strip())
    return unit if unit else rule_normalize(name)


@lru_cache(maxsize=1)
def load_chart_units() -> list[tuple[str, str, str]]:
    """조직도의 (부문, 상위조직, 조직명) 목록 (문서 순서, 중복 포함)."""
    chart = json.loads(ORG_CHART_PATH.read_text(encoding="utf-8"))
    units: list[tuple[str, str, str]] = []

    def walk(node, section, parent):
        units.append((section, parent, node["name"]))
        for c in node.get("children", []):
            walk(c, section, node["name"])

    for top in chart["organization"]:
        for c in top.get("children", []):
            walk(c, top["name"], top["name"])
    return units


def org_type(name):
    """조직 유형 분류 (휴리스틱)."""
    if name is None or not isinstance(name, str):
        return "미상"
    if re.search(r"(국제학사|기숙사|사감)", name):
        return "기숙사"
    if "대학원" in name:
        return "대학원"
    if re.search(r"(학과|학부|전공|협동과정|교양영어|교양국어|로욜라국제대학)$", name):
        return "학과·전공"
    if re.search(r"(팀|처|실|지원단|추진단|사업단|봉사실|고시반)", name) and "연구" not in name:
        return "행정부서"
    if re.search(r"(센터|연구소|교육원|도서관|출판부|메리홀|박물관|대학|그룹|하계대학)", name):
        return "부속기관·센터"
    return "기타"
